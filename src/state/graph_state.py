"""Shared LangGraph state for the Stage 1 pLCA-agents workflow.

`GraphState` is the shared state object passed throughout the LangGraph
workflow as the Inventory Classification Agent and Estimation
Recommendation Agent execute and the shared LCI Development Workbook is
reviewed by a human. It does not define new data structures; it only
references the existing `Technology`, `InventoryClassificationPackage`,
`ConfirmedInventoryPackage`, and `RecommendationPackage` Pydantic
models so that the graph, the agents, the Human-in-the-Loop
infrastructure, and the orchestrator all share one canonical
representation of the workflow data.

- `technology` is the user-provided description of the laboratory-scale
  technology. It is treated as immutable input: it is loaded once from
  `technology.yaml` and read by the agents, never modified during the
  workflow.
- `inventory_classification` is the original output generated by the
  Inventory Classification Agent. It is set exactly once and never
  modified afterward -- it is not the human-reviewed result. `None`
  until the agent has run.
- `lci_workbook_path` is the path to the shared LCI Development
  Workbook (`lci_development_workbook.xlsx`), the single
  Human-in-the-Loop artifact used across all workflow stages. Set once
  the workbook has been exported; `None` beforehand.
- `confirmed_inventory` is the human-reviewed inventory imported from
  Worksheet 1 of that same workbook after the human review interrupt is
  resumed. It becomes the authoritative inventory package for
  downstream agents -- the Estimation Recommendation Agent consumes
  only this field (plus `technology`), never reading Excel directly.
  `None` until the reviewed workbook has been imported.
- `recommendation_package` is the output of the Estimation
  Recommendation Agent: one recommended (and, where relevant, one more
  representative) estimation method per confirmed inventory. `None`
  until the agent has run. It is exported to Worksheet 2 ("Estimation
  Recommendations") of the same shared workbook.

Future work: A future version of the framework may introduce a
dedicated `WorkflowState` model to track workflow execution metadata
(e.g. iteration count, convergence status, retry information, or
checkpoint state beyond what LangGraph's own checkpointer already
tracks). This can be added without changing the models referenced here.
"""

from typing import TypedDict

from src.models.confirmed_inventory import ConfirmedInventoryPackage
from src.models.inventory_classification import InventoryClassificationPackage
from src.models.recommendation import RecommendationPackage
from src.models.technology import Technology


class GraphState(TypedDict):
    """Shared state passed between LangGraph nodes in the Stage 1 workflow."""

    technology: Technology
    inventory_classification: InventoryClassificationPackage | None
    confirmed_inventory: ConfirmedInventoryPackage | None
    lci_workbook_path: str | None
    recommendation_package: RecommendationPackage | None
